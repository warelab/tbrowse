#!/usr/bin/env node
/**
 * Regenerates surface-used-by-tbrowse.txt: every name the viewer's src/
 * imports or re-exports from 'tbrowse-core', in any of these forms (across
 * lines):  import { a, type B } from 'tbrowse-core'
 *          import type { C } from 'tbrowse-core'
 *          export { d } from 'tbrowse-core' / export type { E } from 'tbrowse-core'
 *          import * as ns from 'tbrowse-core' + `ns.member` property reads
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const viewerSrc = resolve(here, '../../../src');
const files = [];
const walk = (d) => { for (const f of readdirSync(d)) { const p = join(d, f); if (statSync(p).isDirectory()) walk(p); else if (/\.(ts|tsx)$/.test(f) && !/\.test\.tsx?$/.test(f)) files.push(p); } };
walk(viewerSrc);
const names = new Set();
for (const p of files) {
  const s = readFileSync(p, 'utf8');
  for (const m of s.matchAll(/(?:import|export)\s+(?:type\s+)?\{([^}]*)\}\s*from\s*['"]tbrowse-core['"]/g)) {
    for (let n of m[1].split(',')) {
      n = n.trim().replace(/^type\s+/, '');
      if (!n) continue;
      names.add(n.split(/\s+as\s+/)[0].trim());
    }
  }
  for (const m of s.matchAll(/import\s+\*\s+as\s+([A-Za-z_$][\w$]*)\s+from\s*['"]tbrowse-core['"]/g)) {
    const ns = m[1];
    for (const u of s.matchAll(new RegExp(`\\b${ns}\\.([A-Za-z_$][\\w$]*)`, 'g'))) names.add(u[1]);
  }
}
const out = ['# Names tbrowse/src imports or re-exports from tbrowse-core (generated by packages/core/scripts/regen-surface.mjs).', ...[...names].sort()].join('\n') + '\n';
writeFileSync(resolve(here, 'surface-used-by-tbrowse.txt'), out);
console.log(`regen-surface: ${names.size} names from ${files.length} files`);
