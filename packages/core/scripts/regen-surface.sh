#!/bin/sh
# Regenerates surface-used-by-tbrowse.txt from the viewer's imports.
cd "$(dirname "$0")/../../.." || exit 1
{
  echo '# Names tbrowse/src imports from tbrowse-core (generated by packages/core/scripts/regen-surface.sh).'
  grep -rhoE "import (type )?\{[^}]*\} from '(tbrowse-core)'" src \
    | sed -E "s/import (type )?\{//; s/\} from '(tbrowse-core)'//" \
    | tr ',' '\n' | sed -E 's/^ *(type )?//; s/ *$//; s/^(.*) as .*$/\1/' | grep -v '^$' | sort -u
} > packages/core/scripts/surface-used-by-tbrowse.txt
